const RECTANGLE_KIND: &str = "rect";

const GENERATED_TS_HEADER: &str = concat!(
    "// This file was generated by [ts-rs](https://github.com/Aleph-Alpha/ts-rs). Do not edit this file manually.\n",
    "// Generated by Inkfinite's binding generator. Run `cargo run -p inkfinite-cli --bin generate-bindings`.\n\n",
);

const GENERATED_JSON_COMMENT: &str = "Generated by Inkfinite's binding generator. Do not edit this file manually.";

fn main() {
    let check = match std::env::args().skip(1).collect::<Vec<_>>().as_slice() {
        [] => false,
        [flag] if flag == "--check" => true,
        [flag] if flag == "--help" || flag == "-h" => {
            println!("Usage: generate-bindings [--check]");
            return;
        }
        _ => {
            eprintln!("usage: generate-bindings [--check]");
            std::process::exit(2);
        }
    };

    if let Err(error) = run(check) {
        eprintln!("binding generation failed: {error}");
        std::process::exit(1);
    }
}

fn run(check: bool) -> Result<(), Box<dyn Error>> {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let artifacts = artifacts()?;
    let mut stale = Vec::new();

    for (relative_path, contents) in artifacts {
        let path = root.join(&relative_path);
        if check {
            match fs::read_to_string(&path) {
                Ok(existing) if existing == contents => {}
                Ok(_) => stale.push(relative_path),
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                    stale.push(relative_path);
                }
                Err(error) => return Err(error.into()),
            }
        } else {
            write_if_changed(&path, &contents)?;
        }
    }

    if stale.is_empty() {
        if check {
            println!("generated bindings are up to date");
        }
        return Ok(());
    }

    eprintln!("generated files are stale:");
    for path in stale {
        eprintln!("  {}", path.display());
    }
    Err("run generate-bindings to refresh generated output".into())
}

fn artifacts() -> Result<BTreeMap<PathBuf, String>, Box<dyn Error>> {
    let mut artifacts = BTreeMap::new();
    insert_schema::<DocumentSnapshot>(&mut artifacts, "schemas/document-snapshot.schema.json")?;
    insert_schema::<TransactionDraft>(&mut artifacts, "schemas/transaction-draft.schema.json")?;
    insert_schema::<Request>(&mut artifacts, "schemas/protocol-request.schema.json")?;
    insert_schema::<Response>(&mut artifacts, "schemas/protocol-response.schema.json")?;
    insert_schema::<ProtocolError>(&mut artifacts, "schemas/protocol-error.schema.json")?;

    artifacts.insert(PathBuf::from("fixtures/native/shape-registry.json"), fixture_json()?);
    artifacts.insert(PathBuf::from("packages/bindings/src/model.ts"), model_bindings());
    artifacts.insert(
        PathBuf::from("packages/bindings/src/transaction.ts"),
        transaction_bindings(),
    );
    artifacts.insert(PathBuf::from("packages/bindings/src/protocol.ts"), protocol_bindings());
    artifacts.insert(PathBuf::from("packages/bindings/src/registry.ts"), registry_bindings());
    artifacts.insert(PathBuf::from("packages/bindings/src/index.ts"), index_bindings());
    Ok(artifacts)
}

fn insert_schema<T: JsonSchema>(
    artifacts: &mut BTreeMap<PathBuf, String>, relative_path: &str,
) -> Result<(), Box<dyn Error>> {
    let mut schema = serde_json::to_value(schemars::schema_for!(T))?;
    if let Some(object) = schema.as_object_mut() {
        object.insert("$comment".into(), Value::String(GENERATED_JSON_COMMENT.into()));
    }
    artifacts.insert(
        PathBuf::from(relative_path),
        format!("{}\n", serde_json::to_string_pretty(&schema)?),
    );
    Ok(())
}

